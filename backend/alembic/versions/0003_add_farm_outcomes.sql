CREATE TABLE IF NOT EXISTS farm_outcomes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id INTEGER NOT NULL REFERENCES fields(id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    period VARCHAR,
    season VARCHAR,
    year INTEGER,
    crop VARCHAR NOT NULL,
    planting_date VARCHAR,
    harvest_date VARCHAR,
    actual_yield_t_ha DOUBLE PRECISION,
    actual_revenue_bdt DOUBLE PRECISION,
    actual_cost_bdt DOUBLE PRECISION,
    actual_water_mm DOUBLE PRECISION,
    estimated_yield_t_ha DOUBLE PRECISION,
    estimated_revenue_bdt DOUBLE PRECISION,
    estimated_water_mm DOUBLE PRECISION,
    yield_variance_pct DOUBLE PRECISION,
    revenue_variance_pct DOUBLE PRECISION,
    water_variance_pct DOUBLE PRECISION,
    management_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS farm_outcomes_field_id_idx ON farm_outcomes(field_id);
CREATE INDEX IF NOT EXISTS farm_outcomes_user_id_idx ON farm_outcomes(user_id);
CREATE INDEX IF NOT EXISTS farm_outcomes_year_season_idx ON farm_outcomes(year, season);
