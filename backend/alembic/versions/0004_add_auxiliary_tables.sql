CREATE TABLE IF NOT EXISTS weather_snapshots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id VARCHAR,
    source VARCHAR,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    date VARCHAR,
    temperature DOUBLE PRECISION,
    rainfall DOUBLE PRECISION,
    soil_moisture DOUBLE PRECISION,
    other_variables TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ml_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id VARCHAR,
    prediction DOUBLE PRECISION,
    model_name VARCHAR,
    model_version VARCHAR,
    metrics JSONB,
    features_used JSONB,
    research_boundary TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS rotation_plans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id VARCHAR,
    optimization_status VARCHAR,
    crop_sequence JSONB,
    objective_value DOUBLE PRECISION,
    constraints_summary JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS adaptive_actions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id VARCHAR,
    action VARCHAR,
    action_type VARCHAR,
    reward DOUBLE PRECISION,
    safety_status VARCHAR,
    state_before JSONB,
    state_after JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS validation_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id VARCHAR,
    validation_type VARCHAR,
    status VARCHAR,
    message TEXT,
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS provenance_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id VARCHAR,
    source VARCHAR,
    source_type VARCHAR,
    mode VARCHAR,
    metadata JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS weather_snapshots_run_id_idx ON weather_snapshots(analysis_run_id);
CREATE INDEX IF NOT EXISTS ml_results_run_id_idx ON ml_results(analysis_run_id);
CREATE INDEX IF NOT EXISTS rotation_plans_run_id_idx ON rotation_plans(analysis_run_id);
CREATE INDEX IF NOT EXISTS adaptive_actions_run_id_idx ON adaptive_actions(analysis_run_id);
CREATE INDEX IF NOT EXISTS validation_results_run_id_idx ON validation_results(analysis_run_id);
CREATE INDEX IF NOT EXISTS provenance_records_run_id_idx ON provenance_records(analysis_run_id);
