-- Description: Table for persistent multi-field agricultural experiment suites, baselines, OVAT sweeps, and invariants.

CREATE TABLE IF NOT EXISTS experiment_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id VARCHAR NOT NULL UNIQUE,
    field_id VARCHAR NOT NULL,
    field_name VARCHAR NOT NULL,
    profile_json JSONB NOT NULL,
    model_version VARCHAR NOT NULL,
    baseline_json JSONB NOT NULL,
    ovat_sensitivity_json JSONB NOT NULL,
    interaction_json JSONB NOT NULL,
    invariants_json JSONB NOT NULL,
    data_status VARCHAR NOT NULL DEFAULT 'SYNTHETIC_TEST_DATA',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS experiment_runs_experiment_id_idx ON experiment_runs(experiment_id);
CREATE INDEX IF NOT EXISTS experiment_runs_field_id_idx ON experiment_runs(field_id);
